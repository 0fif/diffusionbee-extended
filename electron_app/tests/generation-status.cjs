const assert = require('assert');
const fs = require('fs');
const source = fs.readFileSync(require('path').join(__dirname, '../src/StableDiffusion.vue'), 'utf8').split('<script>')[1].split('</script>')[0]
    .replace(/^import .*$/gm, '').replace(/let notification_sound = .*\n/, '').replace('export default', 'return');
const sent = [];
const component = new Function('send_to_py', 'get_tokens', 'notification_sound', source)(message => sent.push(message), () => [], {play(){}});
const vm = {...component.data(), $parent:{app_state:{app_data:{settings:{notification_sound:false}}}}, $set:(obj,key,value)=>{obj[key]=value;}};
for (const [name, method] of Object.entries(component.methods)) vm[name] = method.bind(vm);
(async () => {
    vm.is_input_avail = true;
    vm.text_to_img({prompt:'test',engine:'mflux',num_steps:4}, {}, 'txt2img');
    assert(!vm.is_input_avail, 'reserve worker immediately, before backend acknowledgment');
    assert.equal(vm.steps, 4);
    await vm.state_msg('stat '+JSON.stringify({event:'stage',message:'Preparing prompt'}));
    assert.equal(vm.generation_state_msg,'Preparing prompt');
    await vm.state_msg('stat '+JSON.stringify({event:'progress',step:1,steps:4,step_seconds:2}));
    await vm.state_msg('dnpr 25');
    assert.equal(vm.step_seconds,2, 'step duration comes from backend, excludes loading');
    vm.interupt();vm.interupt();
    assert.equal(sent.filter(s=>s==='t2im __stop__').length,1);
    assert(!vm.is_input_avail, 'Stop waits for worker exit');
    await vm.state_msg('stat '+JSON.stringify({event:'stage',message:'Late stage'}));
    await vm.state_msg('nwim {"generated_img_path":"late.png"}');
    assert.equal(vm.generation_state_msg,'Stopping…');
    await vm.state_msg('inrd');
    assert(vm.is_input_avail);assert.equal(vm.generation_state_msg,'Stopped');
    let finish;
    vm.text_to_img({prompt:'test',num_steps:3},{on_img:()=>new Promise(resolve=>{finish=resolve;})},'txt2img');
    await vm.state_msg('nwim {"generated_img_path":"test.png","timings":{"generation":6},"peak_memory_bytes":1000}');
    const ready=vm.state_msg('inrd');
    assert(!vm.is_input_avail, 'image compositing completes before next job');
    finish();await ready;
    assert(vm.is_input_avail);assert.equal(vm.generation_state_msg,'Complete');
    assert.equal(vm.diagnostics.timings.generation,6);
    vm.text_to_img({prompt:'test',num_steps:3},{on_err:()=>{}},'txt2img');
    await vm.state_msg('errr failed');await vm.state_msg('inrd');
    assert.equal(vm.generation_state_msg,'Failed');assert(vm.is_input_avail);
    vm.text_to_img({prompt:'test',num_steps:3},{on_img:()=>Promise.reject(new Error('save failed')),on_err:()=>{}},'txt2img');
    await vm.state_msg('nwim {"generated_img_path":"test.png"}');await vm.state_msg('inrd');
    assert.equal(vm.generation_state_msg,'Failed');assert(vm.is_input_avail);
    console.log('PASS: real step count, startup exclusion, Stop acknowledgment, late events, async finishing, failure, subsequent runs');
})().catch(error=>{console.error(error);process.exitCode=1;}).finally(()=>clearInterval(vm.generation_loop));
